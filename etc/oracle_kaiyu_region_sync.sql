CREATE TABLE YLZ_USER.KAIYU_REGION_SYNC_DAY (
 SHOP_ID VARCHAR2(64 CHAR) NOT NULL,
 STAT_DATE DATE NOT NULL,
 MALL_ID NUMBER(20) NOT NULL,
 SHOP_NAME VARCHAR2(255 CHAR) NOT NULL,
 SYNC_STATE VARCHAR2(16 CHAR) NOT NULL,
 RECORD_COUNT NUMBER(10) NOT NULL,
 FETCHED_AT TIMESTAMP NOT NULL,
 LAST_SUCCESS_AT TIMESTAMP,
 ERROR_MESSAGE VARCHAR2(1000 CHAR),
 CONSTRAINT PK_KAIYU_REGION_SYNC_DAY PRIMARY KEY (SHOP_ID, STAT_DATE),
 CONSTRAINT CK_KAIYU_REGION_SYNC_STATE CHECK (SYNC_STATE IN ('success','empty','failed'))
)
